import { rng, gaussian } from '../lib/rng'

/** Hourly connection counts for a sparkline, with an optional late surge. */
function hourly(seed, base, jitter, surgeAt = null, surge = 1) {
  const r = rng(seed)
  return Array.from({ length: 24 }, (_, h) => {
    const diurnal = 0.55 + 0.45 * Math.sin(((h - 6) / 24) * Math.PI * 2) ** 2
    let v = base * diurnal + gaussian(r) * jitter
    if (surgeAt !== null && h >= surgeAt) v *= surge
    return Math.max(0, Math.round(v))
  })
}

